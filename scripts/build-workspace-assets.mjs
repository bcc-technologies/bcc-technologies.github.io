import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { WORKSPACE_ASSET_DIRECTORY, WORKSPACE_DASHBOARD_ASSETS } from "./workspace-assets.manifest.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const importPattern = /@import\s+url\("([^"\r\n]+)"\)(?:\s+layer\(([^)\r\n]+)\))?\s*;/g;
const supabaseCdnTag = '<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.110.8" defer data-bcc-supabase-js="true"></script>';
const expectedFiles = new Map();
const changes = [];

function read(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

function digest(source) {
  return crypto.createHash("sha256").update(source).digest("hex").slice(0, 16);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function flattenCss(relativePath, ancestry = []) {
  if (ancestry.includes(relativePath)) {
    throw new Error(`Import CSS cíclico: ${[...ancestry, relativePath].join(" -> ")}`);
  }

  const directory = path.posix.dirname(relativePath.replaceAll(path.sep, "/"));
  return read(relativePath).replace(importPattern, (statement, reference, layer) => {
    if (/^(?:https?:|\/\/|data:)/i.test(reference)) {
      throw new Error(`Import CSS externo no soportado en ${relativePath}: ${reference}`);
    }

    const importedPath = path.posix.normalize(path.posix.join(directory, reference));
    if (importedPath.startsWith("../")) {
      throw new Error(`Import CSS fuera del proyecto en ${relativePath}: ${reference}`);
    }

    const imported = flattenCss(importedPath, [...ancestry, relativePath]).trim();
    return layer ? `@layer ${layer} {\n${imported}\n}` : imported;
  });
}

function bundleScripts(sources) {
  return [
    "/* Generated by scripts/build-workspace-assets.mjs. Do not edit directly. */",
    ...sources.flatMap(source => [
      `/* Source: ${source} */`,
      read(source).trimEnd(),
      ""
    ])
  ].join("\n");
}

function bundleCss(entry) {
  return [
    "/* Generated by scripts/build-workspace-assets.mjs. Do not edit directly. */",
    flattenCss(entry).trim(),
    ""
  ].join("\n");
}

function queue(relativePath, source) {
  expectedFiles.set(relativePath, source);
}

function replaceDashboardReferences(dashboard) {
  const page = dashboard.page;
  const source = read(page);
  const lineEnding = source.includes("\r\n") ? "\r\n" : "\n";
  const normalizedSource = source.replace(/\r+\n/g, "\n").replaceAll("\r", "\n");
  const css = expectedFiles.get(dashboard.cssFile);
  const script = expectedFiles.get(dashboard.scriptFile);
  const cssVersion = digest(css);
  const scriptVersion = digest(script);
  const cssTag = `<link rel="stylesheet" href="${dashboard.cssFile}?v=${cssVersion}">`;
  const englishPage = `/en/${page}`;
  const localeTags = [
    `  <link rel="alternate" hreflang="es" href="/${page}" />`,
    `  <link rel="alternate" hreflang="en" href="${englishPage}" />`,
    '  <meta name="bcc-lang-targets" content="es,en" />'
  ].join("\n");
  const scriptTags = [
    `  ${supabaseCdnTag}`,
    `  <script src="${dashboard.scriptFile}?v=${scriptVersion}" defer></script>`
  ].join("\n");
  const finalScript = dashboard === WORKSPACE_DASHBOARD_ASSETS.client ? "dashboard.js" : "staff-dashboard.js";
  const legacyScripts = new RegExp(
    `  <script src="js/i18n\\.js" defer><\\/script>[\\s\\S]*?  <script src="js/${finalScript.replace(".", "\\.")}" defer><\\/script>`
  );
  const compiledScript = new RegExp(
    `<script src="${dashboard.scriptFile.replaceAll("/", "\\/").replaceAll(".", "\\.")}\\?v=[^"]+" defer><\\/script>`
  );
  const compiledRuntime = new RegExp(`[ \\t]*${escapeRegExp(supabaseCdnTag)}\\s*${compiledScript.source}`);

  const withoutLocaleTags = normalizedSource
    .replace(`  <link rel="alternate" hreflang="es" href="/${page}" />\n`, "")
    .replace(`  <link rel="alternate" hreflang="en" href="${englishPage}" />\n`, "")
    .replace('  <meta name="bcc-lang-targets" content="es,en" />\n', "");
  const withCss = withoutLocaleTags.replace(
    /<link rel="stylesheet" href="(?:css\/pages\/dashboard-(?:client|staff)\.css|assets\/workspace\/dashboard-(?:client|staff)\.css\?v=[^"]+)">/,
    `${cssTag}\n${localeTags}`
  );
  const updated = legacyScripts.test(withCss)
    ? withCss.replace(legacyScripts, scriptTags)
    : withCss.replace(compiledRuntime.test(withCss) ? compiledRuntime : compiledScript, scriptTags);
  if (!withCss.includes(`${dashboard.cssFile}?v=${cssVersion}`)
    || !updated.includes(`${dashboard.scriptFile}?v=${scriptVersion}`)
    || !updated.includes(supabaseCdnTag)) {
    throw new Error(`No se pudieron actualizar las referencias compiladas de ${page}.`);
  }

  queue(page, updated.replaceAll("\n", lineEnding));
}

for (const dashboard of Object.values(WORKSPACE_DASHBOARD_ASSETS)) {
  queue(dashboard.cssFile, bundleCss(dashboard.cssEntry));
  queue(dashboard.scriptFile, bundleScripts(dashboard.scripts));
}

for (const dashboard of Object.values(WORKSPACE_DASHBOARD_ASSETS)) replaceDashboardReferences(dashboard);

const manifest = {
  version: 1,
  bundles: Object.fromEntries(Object.entries(WORKSPACE_DASHBOARD_ASSETS).map(([role, dashboard]) => [role, {
    css: { file: dashboard.cssFile, version: digest(expectedFiles.get(dashboard.cssFile)) },
    javascript: { file: dashboard.scriptFile, version: digest(expectedFiles.get(dashboard.scriptFile)) }
  }]))
};
queue(`${WORKSPACE_ASSET_DIRECTORY}/manifest.json`, `${JSON.stringify(manifest, null, 2)}\n`);

for (const [relativePath, expected] of expectedFiles) {
  const absolutePath = path.join(root, relativePath);
  const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, "utf8") : null;
  if (current === expected) continue;
  changes.push(relativePath);
  if (!checkOnly) {
    fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
    fs.writeFileSync(absolutePath, expected);
  }
}

if (checkOnly && changes.length) {
  console.error(`Los assets compilados del workspace están desactualizados:\n- ${changes.join("\n- ")}`);
  process.exit(1);
}

console.log(changes.length
  ? `Assets del workspace ${checkOnly ? "verificados" : "generados"}: ${changes.length}.`
  : "Assets del workspace al día.");
